def test_fsusage_is_read_with_and_without_mount_prefix(rec_dir):
    (rec_dir / "fsusage.json").write_text(json.dumps({"/": {"size": 9, "used": 5}, "/mnt/t": {"size": 9, "used": 7},
                                                      "/mnt/t/home": {"size": 9, "used": 3}}))
    assert RecoveryData.from_dir(rec_dir).usage == {"/": 5, "/mnt/t": 7, "/mnt/t/home": 3}
    assert RecoveryData.from_dir(rec_dir, mount_prefix="/mnt/t").usage == {"/": 7, "/home": 3}   # Host-"/" zählt nicht
