def test_shrink_layout_to_128_gib(rec_dir, tmp_path):
    rec = RecoveryData.from_dir(rec_dir)
    target = 128 * GIB
    plan = build_layout_plan(rec, "/dev/vda", "geheim", target_size=target, shrink=True, workdir=tmp_path / "w")
    parts, dump = parts_of(plan)
    assert parts[1] == (2048, 1998848) and parts[2][1] == 2000896          # EFI und /boot unverändert
    assert parts[3][0] == 4001792 and parts[3][0] % 2048 == 0
    end = parts[3][0] + parts[3][1]
    assert end <= target // 512 - 33 and end > target // 512 - 33 - 2048    # nutzt den Rest bis zum GPT-Backup
    assert "last-lba" not in dump and "label-id: 2AC01B6E-E4F8-4153-AEA7-48BEDE2CE30B" in dump
    assert "uuid=04492FD8-7696-47D5-AB26-38A34FFC6E35" in dump           # PARTUUID bleibt
    # LVM-Metadaten: kleineres PV, LVs lückenlos, UUIDs unverändert
    vg = parse_lvm((tmp_path / "w" / "lvm-vg.vg").read_text())["vg"]
    pv = vg["physical_volumes"]["pv0"]
    assert pv["id"] == "PV-UUID-1234" and vg["id"].startswith("AbCdEf")
    assert pv["dev_size"] * 512 <= parts[3][1] * 512 - shrink.LUKS_OVERHEAD
    root, swap = vg["logical_volumes"]["root"], vg["logical_volumes"]["swap"]
    assert root["id"] == "root-lv-id"
    re_, se = root["segment1"]["extent_count"], swap["segment1"]["extent_count"]
    assert re_ * 4 * MIB >= min_with_reserve(40 * GIB)                    # belegt + Reserve
    assert se * 4 * MIB == max(GIB, int(16 * GIB * target / DISK_SIZE) // (4 * MIB) * 4 * MIB)
    assert swap["segment1"]["stripes"] == ["pv0", re_]
    assert re_ + se <= pv["pe_count"] == (pv["dev_size"] - 2048) // 8192
    # pvcreate/vgcfgrestore nutzen die angepasste Datei
    assert any(str(tmp_path / "w" / "lvm-vg.vg") in s.argv for s in plan.steps if s.argv[0] in ("pvcreate", "vgcfgrestore"))
    # Plan zeigt alt/neu
    assert any("->" in l and "vg/root" in l for l in plan.summary) and plan.resizes
    assert any(r.name == "/dev/nvme0n1p1" and r.old == r.new and r.note == "fest" for r in plan.resizes)


def test_shrink_is_deterministic(rec_dir, tmp_path):
    rec = RecoveryData.from_dir(rec_dir)
    a = build_layout_plan(rec, "/dev/vda", "x", target_size=100 * GIB, shrink=True, workdir=tmp_path / "a")
    b = build_layout_plan(rec, "/dev/vda", "x", target_size=100 * GIB, shrink=True, workdir=tmp_path / "b")
    assert [r.__dict__ for r in a.resizes] == [r.__dict__ for r in b.resizes]
    assert (tmp_path / "a" / "lvm-vg.vg").read_text() == (tmp_path / "b" / "lvm-vg.vg").read_text()


def test_not_smaller_is_unchanged_even_with_shrink(rec_dir):
    plan = build_layout_plan(RecoveryData.from_dir(rec_dir), "/dev/vda", "x", target_size=DISK_SIZE, shrink=True)
    assert not plan.resizes
    assert next(s.stdin for s in plan.steps if s.title == "Partitionstabelle anlegen").count("last-lba") == 1


def test_too_small_reports_minimum(rec_dir, tmp_path):
    rec = RecoveryData.from_dir(rec_dir)
    with pytest.raises(RescueError) as e:
        build_layout_plan(rec, "/dev/vda", "x", target_size=50 * GIB, shrink=True, workdir=tmp_path)
    m = re.search(r"mindestens (\d+(?:\.\d+)?) GiB nötig", str(e.value))
    assert m and "auch mit" in str(e.value)
    need = float(m[1])
    assert 50 < need < 70                     # 48 GiB + 1 GiB EFI + 1 GiB /boot + Swap-Minimum + Overhead
    # mit der genannten Mindestgröße klappt es
    build_layout_plan(rec, "/dev/vda", "x", target_size=int(need * GIB), shrink=True, workdir=tmp_path)


def test_usage_falls_back_to_snapshot_size(rec_dir, tmp_path):
    (rec_dir / "fsusage.json").unlink()
    rec = RecoveryData.from_dir(rec_dir)
    plan = build_layout_plan(rec, "/dev/vda", "x", target_size=128 * GIB, shrink=True, snapshot_size=40 * GIB,
                             workdir=tmp_path)
    assert any("Snapshot-Größe" in w for w in plan.warnings)
    root = next(r for r in plan.resizes if r.name == "vg/root")
    assert root.new >= min_with_reserve(40 * GIB) - 4 * MIB


@pytest.mark.parametrize("mode", ["keep", "none", "new"])
def test_all_encryption_modes_shrink(rec_dir, tmp_path, mode):
    rec = RecoveryData.from_dir(rec_dir)
    plan = build_layout_plan(rec, "/dev/vda", "x" if mode == "keep" else None, target_size=128 * GIB, shrink=True,
                             encryption=mode, new_passphrase="neue-pass-1" if mode == "new" else None,
                             workdir=tmp_path)
    cmds = [s.argv[0] + " " + (s.argv[1] if len(s.argv) > 1 else "") for s in plan.steps]
    assert ("cryptsetup luksHeaderRestore" in cmds) == (mode == "keep")
    assert ("cryptsetup luksFormat" in cmds) == (mode == "new")
    assert "pvcreate -ff" in cmds


def test_multi_pv_and_thin_lvs_are_refused():
    two = VG_TEXT.replace("\t}\n\n\tlogical_volumes", "\t\tpv1 {\n\t\t\tid = \"x\"\n\t\t\tdev_size = 1\n\t\t\tpe_start = 1\n"
                          "\t\t\tpe_count = 1\n\t\t}\n\t}\n\n\tlogical_volumes", 1)
    with pytest.raises(RescueError, match="mehrere"):
        shrink.read_vg(two, "vg")
    thin = VG_TEXT.replace('type = "striped"', 'type = "thin-pool"', 1)
    with pytest.raises(RescueError, match="nicht linear"):
        shrink.read_vg(thin, "vg")


