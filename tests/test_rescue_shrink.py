USED = {"/": 40 * GIB}
# echte dm-Namen: Volume Group "vg", LV "root"/"swap" -> vg-root / vg-swap
LSBLK_S = json.loads(json.dumps(LSBLK).replace("vg--root", "vg-root").replace("vg--swap", "vg-swap"))


